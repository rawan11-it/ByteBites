import React, { useState } from 'react';
import { useApp } from '../context/AppContext';
import { Recipe } from '../types';
import { RecipeDetailView } from '../components/RecipeDetailView';

export const WheelScreen: React.FC = () => {
  const { userId, t, theme, language, fridgeIngredients, isWheelIngredientMode, registerRecipe } = useApp();
  const isDark = theme === 'dark';
  const isArabic = language === 'ar';

  const items = t.wheel.categories;

  const [rotation, setRotation] = useState(0);
  const [isSpinning, setIsSpinning] = useState(false);
  const [selectedItem, setSelectedItem] = useState<string | null>(items[0]);

  // Byte AI Recipe Generation State
  const [generatedRecipe, setGeneratedRecipe] = useState<Recipe | null>(null);
  const [isLoadingRecipe, setIsLoadingRecipe] = useState(false);
  const [errorMessage, setErrorMessage] = useState<string | null>(null);

  const colors = [
    '#006853',
    '#00647d',
    '#00f9cb',
    '#0aceff',
    '#7c3aed',
  ];

  const generateRecipeForCategory = async (category: string, ingredientsToSend: string[]) => {
    setIsLoadingRecipe(true);
    setErrorMessage(null);

    try {
      const response = await fetch('/api/ai/recipe', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          promptType: 'wheel',
          category,
          ingredients: ingredientsToSend,
          language,
          userId,
        }),
      });

      const contentType = response.headers.get('content-type') || '';
      if (!contentType.includes('application/json')) {
        throw new Error('Invalid response format');
      }

      const data = await response.json();
      if (data.success && data.recipe) {
        registerRecipe(data.recipe);
        setGeneratedRecipe(data.recipe);
      } else {
        throw new Error(data.userMessage || data.error || 'Failed to generate recipe');
      }
    } catch (err: any) {
      console.error('Error generating recipe with Byte:', err);
      setErrorMessage(
        isArabic
          ? 'عذراً، حدث خطأ أثناء ابتكار الوصفة مع بايت. يرجى المحاولة مرة أخرى!'
          : 'Sorry, an error occurred while Byte was crafting the recipe. Please try again!'
      );
    } finally {
      setIsLoadingRecipe(false);
    }
  };

  const handleSpin = () => {
    if (isSpinning || isLoadingRecipe) return;
    setIsSpinning(true);
    setErrorMessage(null);

    const randomSlice = Math.floor(Math.random() * items.length);
    const extraSpins = 5 + Math.floor(Math.random() * 4);
    const sliceAngle = 360 / items.length;

    // Calculate target offset to align chosen slice with top pointer (0 deg)
    const targetOffset = (360 - (randomSlice * sliceAngle + sliceAngle / 2)) % 360;
    const currentRotationMod = rotation % 360;
    let delta = targetOffset - currentRotationMod;
    if (delta <= 0) {
      delta += 360;
    }
    const newRotation = rotation + extraSpins * 360 + delta;
    setRotation(newRotation);

    setTimeout(() => {
      setIsSpinning(false);
      const chosenCategory = items[randomSlice];
      setSelectedItem(chosenCategory);

      // Record session in database
      fetch('/api/wheel/session', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          userId,
          category: chosenCategory,
          isIngredientMode: isWheelIngredientMode,
          ingredientsUsed: fridgeIngredients,
        }),
      }).catch(err => console.error('Error recording wheel session in DB:', err));

      // If user came from Saver in ingredient mode with saved ingredients, immediately trigger Byte!
      if (isWheelIngredientMode && Array.isArray(fridgeIngredients) && fridgeIngredients.length > 0) {
        generateRecipeForCategory(chosenCategory, fridgeIngredients);
      }
    }, 3500);
  };

  const handleCookForMe = async () => {
    if (!selectedItem || isLoadingRecipe) return;
    const ingredientsToSend =
      isWheelIngredientMode && Array.isArray(fridgeIngredients) && fridgeIngredients.length > 0
        ? fridgeIngredients
        : [];
    generateRecipeForCategory(selectedItem, ingredientsToSend);
  };

  const R = 98;
  const sliceAngle = 360 / items.length;

  // If a recipe was generated by Byte, display it inside the Wheel screen seamlessly!
  if (generatedRecipe) {
    return (
      <div
        id="wheel-screen-container"
        className={`min-h-screen pt-20 pb-32 px-6 max-w-4xl mx-auto transition-colors duration-200 ${
          isDark ? 'bg-[#002117] text-white' : 'bg-[#d6fff6] text-[#00352f]'
        }`}
      >
        <RecipeDetailView
          recipe={generatedRecipe}
          onBack={() => setGeneratedRecipe(null)}
          backButtonLabel={isArabic ? 'الرجوع للعجلة' : 'Back to Wheel'}
        />
      </div>
    );
  }

  return (
    <div
      id="wheel-screen-container"
      className={`min-h-screen pt-20 pb-32 px-6 max-w-lg mx-auto transition-colors duration-200 flex flex-col items-center text-center ${
        isDark ? 'bg-[#002117] text-white' : 'bg-[#d6fff6] text-[#00352f]'
      }`}
    >
      {/* Title and Intro */}
      <div className="mb-4 w-full">
        <h2 className={`font-headline-md text-2xl font-bold mb-2 flex items-center justify-center gap-2 ${isDark ? 'text-[#00f9cb]' : 'text-[#006853]'}`}>
          <span>{t.wheel.title}</span>
          <span>🎡</span>
        </h2>
        <p className={`font-body-md text-sm leading-relaxed max-w-xs mx-auto ${isDark ? 'text-white/80' : 'text-[#00352f]'}`}>
          {t.wheel.subtitle}
        </p>
      </div>

      {/* Interactive Wheel Graphic */}
      <div className="relative my-4 flex items-center justify-center">
        {/* Pointer Arrow */}
        <div className="absolute -top-3 z-30 transform drop-shadow-md">
          <div className="w-0 h-0 border-l-[14px] border-l-transparent border-r-[14px] border-r-transparent border-t-[22px] border-t-[#00f9cb]" />
        </div>

        {/* Wheel Canvas */}
        <div
          id="roulette-wheel"
          className="w-64 h-64 md:w-72 md:h-72 rounded-full border-4 border-[#00f9cb]/60 shadow-[0_0_35px_rgba(0,249,203,0.3)] relative overflow-hidden flex items-center justify-center"
          style={{
            transform: `rotate(${rotation}deg)`,
            transition: isSpinning ? 'transform 3.5s cubic-bezier(0.15, 0.9, 0.2, 1)' : 'none',
          }}
        >
          <svg
            viewBox="-100 -100 200 200"
            className="w-full h-full"
          >
            {items.map((cat, idx) => {
              const startAngle = idx * sliceAngle;
              const endAngle = (idx + 1) * sliceAngle;
              const midAngle = idx * sliceAngle + sliceAngle / 2;

              const startRad = (startAngle * Math.PI) / 180;
              const endRad = (endAngle * Math.PI) / 180;

              const x1 = R * Math.sin(startRad);
              const y1 = -R * Math.cos(startRad);
              const x2 = R * Math.sin(endRad);
              const y2 = -R * Math.cos(endRad);

              const pathData = `M 0 0 L ${x1.toFixed(3)} ${y1.toFixed(3)} A ${R} ${R} 0 0 1 ${x2.toFixed(3)} ${y2.toFixed(3)} Z`;

              return (
                <g key={cat}>
                  <path
                    d={pathData}
                    fill={colors[idx % colors.length]}
                    stroke="rgba(255,255,255,0.25)"
                    strokeWidth="1"
                    style={{ textDecorationLine: 'none' }}
                  />
                  <g transform={`rotate(${midAngle}) translate(0, -58)`}>
                    <text
                      x="0"
                      y="0"
                      fill="#000000"
                      fontSize="12"
                      fontWeight="700"
                      textAnchor="middle"
                      dominantBaseline="central"
                      className="font-headline-md select-none pointer-events-none"
                      style={{
                        width: 'auto',
                        textDecoration: 'none',
                        textDecorationLine: 'none',
                        fontSize: '12px',
                        lineHeight: '12px',
                      }}
                    >
                      {cat}
                    </text>
                  </g>
                </g>
              );
            })}
          </svg>

          {/* Center Mascot Hub */}
          <div className="absolute w-16 h-16 rounded-full bg-[#002117] border-2 border-[#00f9cb] shadow-lg flex items-center justify-center z-20 pointer-events-none">
            <img
              src="https://lh3.googleusercontent.com/aida-public/AB6AXuAPMK2YHfOlYnPH6o4N91cvk5BVN11bLZwwE2QFpSoto2fqAF01GUz1YY3xq4htI5n_BNWGE67EDXglpSgLWxHSLA-HmCm8KMLg8yYzlicLG3Dvq2d7NDdGCFAc5M-AAc82ZwBBQLjolAd-tnX6mL_FypUaI56vLXcFNADYHil0tqJC7SCMhSJQW-oqgaqL1guKcW2eFIioVYODY7fYBduaW5PB1oQu9F2E25sAl6PyTdXpPWJ71QuHvYAQbkgf42i__m-JnnGUIbiaCg"
              alt="Byte center"
              className="w-12 h-12 object-contain rounded-full"
            />
          </div>
        </div>
      </div>

      {/* Spin Button */}
      <button
        id="wheel-spin-button"
        onClick={handleSpin}
        disabled={isSpinning || isLoadingRecipe}
        className={`w-full max-w-xs py-3.5 px-6 rounded-full font-headline-md text-base transition-all active:scale-95 duration-200 border cursor-pointer mt-3 mb-2 shadow-md ${
          isSpinning || isLoadingRecipe
            ? 'opacity-60 cursor-not-allowed bg-gray-600 text-white'
            : isDark
            ? 'bg-[#00f9cb] text-[#00352f] hover:bg-[#00e9be] border-transparent font-bold'
            : 'bg-[#006853] text-white hover:bg-[#005a48] border-transparent font-bold'
        }`}
      >
        {isSpinning ? t.wheel.spinning : t.wheel.spinBtn}
      </button>

      {/* Loading State Banner */}
      {isLoadingRecipe && (
        <div
          id="wheel-byte-loading-card"
          className={`w-full mt-4 p-6 rounded-3xl border text-center animate-pulse ${
            isDark
              ? 'glass-panel border-purple-500/40 bg-gradient-to-r from-purple-900/30 via-[#00f9cb]/20 to-purple-900/30'
              : 'bg-white/95 border-purple-400/40 shadow-lg'
          }`}
        >
          <div className="w-16 h-16 mx-auto mb-3 relative">
            <img
              src="https://lh3.googleusercontent.com/aida-public/AB6AXuAPMK2YHfOlYnPH6o4N91cvk5BVN11bLZwwE2QFpSoto2fqAF01GUz1YY3xq4htI5n_BNWGE67EDXglpSgLWxHSLA-HmCm8KMLg8yYzlicLG3Dvq2d7NDdGCFAc5M-AAc82ZwBBQLjolAd-tnX6mL_FypUaI56vLXcFNADYHil0tqJC7SCMhSJQW-oqgaqL1guKcW2eFIioVYODY7fYBduaW5PB1oQu9F2E25sAl6PyTdXpPWJ71QuHvYAQbkgf42i__m-JnnGUIbiaCg"
              alt="Byte Cooking"
              className="w-full h-full object-contain animate-bounce"
            />
          </div>
          <p className={`font-headline-md text-sm md:text-base font-bold mb-1 ${isDark ? 'text-[#00f9cb]' : 'text-[#006853]'}`}>
            {isArabic ? 'بايت يبتكر وصفتك اللذيذة...' : 'Byte is crafting your delicious recipe...'}
          </p>
          <p className={`text-xs font-body-md ${isDark ? 'text-white/70' : 'text-[#00352f]'}`}>
            {isArabic ? `بناءً على اختيارك: ${selectedItem}` : `Based on your selection: ${selectedItem}`}
          </p>
        </div>
      )}

      {/* Error Message if any */}
      {errorMessage && (
        <div className="w-full mt-3 p-4 rounded-2xl bg-red-500/20 border border-red-500/40 text-red-200 text-xs">
          <p className="mb-2">{errorMessage}</p>
          <button
            onClick={handleCookForMe}
            className="px-4 py-1.5 rounded-full bg-red-500 text-white font-bold text-xs hover:bg-red-600 transition-colors"
          >
            {isArabic ? 'حاول مرة أخرى' : 'Try Again'}
          </button>
        </div>
      )}

      {/* Result Display & Cook for Me Button */}
      {selectedItem && !isLoadingRecipe && (
        <div className="w-full mt-3 animate-fade-in space-y-4">
          <div
            className={`p-4 rounded-2xl border ${
              isDark ? 'glass-panel border-[#00f9cb]/30' : 'bg-white/90 border-[#006853]/20 shadow-sm'
            }`}
          >
            <span className={`text-xs block mb-1 ${isDark ? 'text-white/70' : 'text-[#00352f]'}`}>
              {t.wheel.congrats}
            </span>
            <span className={`font-headline-md text-lg font-bold ${isDark ? 'text-[#00f9cb]' : 'text-[#006853]'}`}>
              ✨ {selectedItem} ✨
            </span>
          </div>

          {/* "خلّ بايت يطبخها لك" button that connects to Byte AI */}
          <button
            id="wheel-cook-for-me-btn"
            onClick={handleCookForMe}
            className="w-full py-4 px-6 rounded-full font-headline-md text-base md:text-lg font-bold shadow-[0_0_25px_rgba(168,85,247,0.4)] hover:shadow-[0_0_35px_rgba(168,85,247,0.6)] hover:scale-[1.02] active:scale-95 transition-all duration-300 flex items-center justify-center gap-2 cursor-pointer"
            style={{
              background: 'linear-gradient(135deg, #a7f3d0 0%, #c084fc 100%)',
              color: '#1e1b4b',
            }}
          >
            <span className="material-symbols-outlined text-xl" style={{ fontVariationSettings: "'FILL' 1" }}>
              auto_awesome
            </span>
            <span>{t.wheel.cookBtn}</span>
          </button>
        </div>
      )}
    </div>
  );
};

