import React, { useState } from 'react';
import { useApp } from '../context/AppContext';
import { Recipe } from '../types';
import { RecipeDetailView } from '../components/RecipeDetailView';

export const SaverScreen: React.FC = () => {
  const { userId, t, theme, language, activeRecipe, fridgeIngredients, setFridgeIngredients, navigateTo, registerRecipe } = useApp();
  const isDark = theme === 'dark';
  const isArabic = language === 'ar';

  const [inputIngredient, setInputIngredient] = useState('');
  const [ingredients, setIngredients] = useState<string[]>(() => {
    return Array.isArray(fridgeIngredients) ? fridgeIngredients : [];
  });

  // Keep global fridgeIngredients synced
  const updateIngredients = (newItems: string[]) => {
    setIngredients(newItems);
    setFridgeIngredients(newItems);
  };

  // Byte AI Recipe Generation State
  const [generatedRecipe, setGeneratedRecipe] = useState<Recipe | null>(null);
  const [isLoadingRecipe, setIsLoadingRecipe] = useState(false);
  const [errorMessage, setErrorMessage] = useState<string | null>(null);

  const handleAddIngredient = (e: React.FormEvent) => {
    e.preventDefault();
    if (inputIngredient.trim() && !ingredients.includes(inputIngredient.trim())) {
      const updated = [...ingredients, inputIngredient.trim()];
      updateIngredients(updated);
      setInputIngredient('');
      setErrorMessage(null);
    }
  };

  const handleRemoveIngredient = (item: string) => {
    const updated = ingredients.filter((i) => i !== item);
    updateIngredients(updated);
  };

  const handleCookForMe = async () => {
    if (isLoadingRecipe) return;
    setErrorMessage(null);

    if (!ingredients || ingredients.length === 0) {
      setErrorMessage(
        isArabic
          ? 'يرجى إضافة مكون أو أكثر من مكونات ثلاجتك أولاً ليتمكن بايت من ابتكار وصفتك!'
          : 'Please add ingredients from your fridge first so Byte can craft your recipe!'
      );
      return;
    }

    setIsLoadingRecipe(true);

    try {
      const response = await fetch('/api/ai/recipe', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          promptType: 'saver',
          ingredients,
          language,
          userId,
        }),
      });

      const contentType = response.headers.get('content-type') || '';
      if (!contentType.includes('application/json')) {
        throw new Error('Invalid response format');
      }

      const data = await response.json();
      if (data.success && data.recipe) {
        registerRecipe(data.recipe);
        setGeneratedRecipe(data.recipe);
      } else {
        throw new Error(data.userMessage || data.error || 'Failed to generate recipe');
      }
    } catch (err: any) {
      console.error('Error generating saver recipe with Byte:', err);
      setErrorMessage(
        isArabic
          ? 'عذراً، حدث خطأ أثناء ابتكار الوصفة مع بايت. يرجى المحاولة مرة أخرى!'
          : 'Sorry, an error occurred while Byte was crafting the recipe. Please try again!'
      );
    } finally {
      setIsLoadingRecipe(false);
    }
  };

  const handleViewDefaultRecipe = () => {
    setGeneratedRecipe(activeRecipe);
  };

  const handleSpinWheelWithIngredients = () => {
    let finalIngredients = [...ingredients];
    if (inputIngredient.trim() && !finalIngredients.includes(inputIngredient.trim())) {
      finalIngredients.push(inputIngredient.trim());
      setInputIngredient('');
    }

    if (finalIngredients.length === 0) {
      setErrorMessage(
        isArabic
          ? 'يرجى إضافة مكون أو أكثر من مكونات ثلاجتك أولاً للف العجلة بمكوناتك!'
          : 'Please add ingredients from your fridge first to spin the wheel with them!'
      );
      return;
    }

    setErrorMessage(null);
    updateIngredients(finalIngredients);
    navigateTo('wheel', undefined, true);
  };

  // If a recipe is being viewed or was generated by Byte, display it inside the Saver screen!
  if (generatedRecipe) {
    return (
      <div
        id="saver-screen-container"
        className={`min-h-screen pt-20 pb-32 px-6 max-w-4xl mx-auto transition-colors duration-200 ${
          isDark ? 'bg-[#002117] text-white' : 'bg-[#d6fff6] text-[#00352f]'
        }`}
      >
        <RecipeDetailView
          recipe={generatedRecipe}
          onBack={() => setGeneratedRecipe(null)}
          backButtonLabel={isArabic ? 'الرجوع للموفر' : 'Back to Saver'}
        />
      </div>
    );
  }

  return (
    <div
      id="saver-screen-container"
      className={`min-h-screen pt-20 pb-32 px-6 max-w-lg mx-auto transition-colors duration-200 flex flex-col items-center text-center ${
        isDark ? 'bg-[#002117] text-white' : 'bg-[#d6fff6] text-[#00352f]'
      }`}
    >
      {/* Title & Subtitle */}
      <div className="mb-6 w-full text-center">
        <h2 className={`font-headline-md text-2xl font-bold mb-2 flex items-center justify-center gap-2 ${isDark ? 'text-[#00f9cb]' : 'text-[#006853]'}`}>
          <span>{t.saver.title}</span>
          <span>🥦</span>
        </h2>
        <p className={`font-body-md text-sm leading-relaxed max-w-xs mx-auto ${isDark ? 'text-white/80' : 'text-[#00352f]'}`}>
          {t.saver.subtitle}
        </p>
      </div>

      {/* Ingredient Search / Add Form */}
      <form onSubmit={handleAddIngredient} className="w-full mb-4">
        <div
          className={`flex items-center rounded-full px-4 py-2 border shadow-inner transition-all ${
            isDark
              ? 'bg-[#062c20] border-white/15 focus-within:border-[#00f9cb]'
              : 'bg-white border-[#006853]/30 focus-within:border-[#006853]'
          }`}
        >
          <button
            type="submit"
            className="w-9 h-9 rounded-full bg-[#00f9cb] text-[#00352f] flex items-center justify-center shrink-0 hover:bg-[#00e9be] transition-colors active:scale-95 cursor-pointer"
            title="Add ingredient"
          >
            <span className="material-symbols-outlined text-xl">add</span>
          </button>
          <input
            id="saver-ingredient-input"
            type="text"
            value={inputIngredient}
            onChange={(e) => setInputIngredient(e.target.value)}
            placeholder={t.saver.searchPlaceholder}
            className={`flex-1 bg-transparent border-none outline-none px-3 font-body-md text-sm ${
              isDark ? 'text-white placeholder-white/50' : 'text-[#00352f] placeholder-gray-500'
            }`}
          />
          <span className={`material-symbols-outlined text-xl ${isDark ? 'text-white/50' : 'text-[#006853]'}`}>
            search
          </span>
        </div>
      </form>

      {/* Added Ingredients Chips */}
      {ingredients.length > 0 ? (
        <div className="flex flex-wrap gap-2 justify-center mb-6 w-full">
          {ingredients.map((item) => (
            <span
              key={item}
              onClick={() => handleRemoveIngredient(item)}
              className={`inline-flex items-center gap-1.5 px-3 py-1 rounded-full text-xs font-label-caps border transition-colors cursor-pointer ${
                isDark
                  ? 'bg-[#00f9cb]/20 text-[#00f9cb] border-[#00f9cb]/40 hover:bg-red-500/20 hover:border-red-400 hover:text-red-300'
                  : 'bg-white text-[#006853] font-bold border-[#006853]/30 shadow-sm hover:bg-red-50 hover:border-red-400 hover:text-red-600'
              }`}
              title="Click to remove"
            >
              {item}
              <span className="material-symbols-outlined text-[14px]">close</span>
            </span>
          ))}
        </div>
      ) : (
        <p className={`text-xs text-center mb-6 px-4 ${isDark ? 'text-white/40' : 'text-[#00352f]/50'}`}>
          {isArabic
            ? '💡 أضف المكونات المتوفرة في ثلاجتك واضغط Enter أو زر +'
            : '💡 Add ingredients available in your fridge and press Enter or +'}
        </p>
      )}

      {/* The Crucial Button: "خلّ بايت يطبخها لك" -> Connected to Byte AI */}
      <button
        id="saver-cook-for-me-btn"
        onClick={handleCookForMe}
        disabled={isLoadingRecipe}
        className={`w-full py-4 px-6 rounded-full font-headline-md text-base md:text-lg font-bold shadow-[0_0_25px_rgba(168,85,247,0.4)] hover:shadow-[0_0_35px_rgba(168,85,247,0.6)] hover:scale-[1.02] active:scale-95 transition-all duration-300 flex items-center justify-center gap-2 mb-3 cursor-pointer ${
          isLoadingRecipe ? 'opacity-60 cursor-not-allowed' : ''
        }`}
        style={{
          background: 'linear-gradient(135deg, #a7f3d0 0%, #c084fc 100%)',
          color: '#1e1b4b',
        }}
      >
        <span className="material-symbols-outlined text-xl" style={{ fontVariationSettings: "'FILL' 1" }}>
          auto_awesome
        </span>
        <span>{isLoadingRecipe ? (isArabic ? 'بايت يبتكر وصفتك...' : 'Byte is cooking...') : t.saver.cookBtn}</span>
      </button>

      {/* Button to navigate to Wheel with ingredients */}
      <button
        id="saver-to-wheel-btn"
        onClick={handleSpinWheelWithIngredients}
        disabled={isLoadingRecipe}
        className={`w-full py-3.5 px-6 rounded-full font-headline-md text-sm md:text-base font-bold border transition-all duration-300 flex items-center justify-center gap-2 mb-6 cursor-pointer hover:scale-[1.01] active:scale-95 ${
          isDark
            ? 'border-[#00f9cb]/40 bg-[#00f9cb]/10 text-[#00f9cb] hover:bg-[#00f9cb]/20 hover:border-[#00f9cb]'
            : 'border-[#006853]/40 bg-[#006853]/10 text-[#006853] hover:bg-[#006853]/20 hover:border-[#006853]'
        }`}
      >
        <span className="material-symbols-outlined text-lg">casino</span>
        <span>{t.saver.spinWheelWithIngredients}</span>
      </button>

      {/* Loading State Banner */}
      {isLoadingRecipe && (
        <div
          id="saver-byte-loading-card"
          className={`w-full mb-6 p-6 rounded-3xl border text-center animate-pulse ${
            isDark
              ? 'glass-panel border-purple-500/40 bg-gradient-to-r from-purple-900/30 via-[#00f9cb]/20 to-purple-900/30'
              : 'bg-white/95 border-purple-400/40 shadow-lg'
          }`}
        >
          <div className="w-16 h-16 mx-auto mb-3 relative">
            <img
              src="https://lh3.googleusercontent.com/aida-public/AB6AXuAPMK2YHfOlYnPH6o4N91cvk5BVN11bLZwwE2QFpSoto2fqAF01GUz1YY3xq4htI5n_BNWGE67EDXglpSgLWxHSLA-HmCm8KMLg8yYzlicLG3Dvq2d7NDdGCFAc5M-AAc82ZwBBQLjolAd-tnX6mL_FypUaI56vLXcFNADYHil0tqJC7SCMhSJQW-oqgaqL1guKcW2eFIioVYODY7fYBduaW5PB1oQu9F2E25sAl6PyTdXpPWJ71QuHvYAQbkgf42i__m-JnnGUIbiaCg"
              alt="Byte Cooking"
              className="w-full h-full object-contain animate-bounce"
            />
          </div>
          <p className={`font-headline-md text-sm md:text-base font-bold mb-1 ${isDark ? 'text-[#00f9cb]' : 'text-[#006853]'}`}>
            {isArabic ? 'بايت يحلل محتويات الثلاجة ويبتكر وصفتك...' : 'Byte is analyzing your fridge ingredients...'}
          </p>
          <p className={`text-xs font-body-md ${isDark ? 'text-white/70' : 'text-[#00352f]'}`}>
            {ingredients.join(' • ')}
          </p>
        </div>
      )}

      {/* Error Message if any */}
      {errorMessage && (
        <div className="w-full mb-6 p-4 rounded-2xl bg-red-500/20 border border-red-500/40 text-red-200 text-xs">
          <p className="mb-2">{errorMessage}</p>
          <button
            onClick={handleCookForMe}
            className="px-4 py-1.5 rounded-full bg-red-500 text-white font-bold text-xs hover:bg-red-600 transition-colors"
          >
            {isArabic ? 'حاول مرة أخرى' : 'Try Again'}
          </button>
        </div>
      )}

      {/* Suggested Recipe AI Card */}
      {!isLoadingRecipe && (
        <div
          id="saver-suggested-recipe-card"
          className={`w-full rounded-3xl p-5 border relative overflow-hidden transition-all duration-300 ${
            isDark
              ? 'glass-card border-white/15 shadow-[0_12px_36px_rgba(0,0,0,0.5)]'
              : 'bg-white/95 border-[#006853]/20 shadow-lg'
          }`}
        >
          {/* AI Badge */}
          <div className="absolute top-4 left-4 z-20">
            <span className="bg-black/60 backdrop-blur-md text-white text-xs font-bold px-3 py-1 rounded-full border border-white/20 flex items-center gap-1">
              <span>AI</span>
              <span className="material-symbols-outlined text-sm">smart_toy</span>
            </span>
          </div>

          {/* Mascot Center Image */}
          <div className="relative w-full h-48 rounded-2xl overflow-hidden mb-4 bg-[#0a231b] flex items-center justify-center">
            <img
              src="https://lh3.googleusercontent.com/aida-public/AB6AXuCwb831DohEUgHQiL9pnL8rBEnZs4vE7-NuYXUpkOzFUO7RGZRzXDOaD-OpY_cJDV-dAzJvPiT-ebQiOM5C-2CaBHAER1cT34C1ZC3CVBTPBheO-tpDMym8d7UUaJMcV7thOcLH8mNKmI7ZqXBk7ibzU3CbYdlmJAtCCt7sUxl9KmSNMnGuaWEuilJlDeNJyKVCDu6z5ScLnWGRL64ByBQhRuPzAmMsEh-4mU2P6puBk35jtC5sK58k0TiuZg20W3_PMUsgVd8JDLCnew"
              alt="Byte Robot Mascot"
              className="w-full h-full object-contain p-2 scale-105"
            />
          </div>

          {/* Title and Time */}
          <div className="flex items-center justify-between mb-3 px-1">
            <h3 className={`font-headline-md text-lg font-bold ${isDark ? 'text-white' : 'text-[#00352f]'}`}>
              {t.saver.recipeName}
            </h3>
            <span className={`text-xs font-label-caps flex items-center gap-1 font-semibold ${isDark ? 'text-white/70' : 'text-[#00352f]'}`}>
              <span>min 45</span>
              <span className="material-symbols-outlined text-[16px]">schedule</span>
            </span>
          </div>

          {/* Easy Tag and View Recipe Button */}
          <div className="flex items-center justify-between mb-5 border-b border-white/10 pb-4">
            <button
              id="saver-view-recipe-action-btn"
              onClick={handleViewDefaultRecipe}
              className={`px-4 py-1.5 rounded-xl border text-xs font-label-caps font-semibold hover:bg-white/10 active:scale-95 transition-all cursor-pointer ${
                isDark
                  ? 'border-white/30 text-white hover:border-[#00f9cb]'
                  : 'border-[#006853] text-[#006853] hover:bg-[#006853]/10'
              }`}
            >
              {t.saver.viewRecipeBtn}
            </button>
            <div className="flex items-center gap-1.5">
              <span className={`w-2.5 h-2.5 rounded-full ${isDark ? 'bg-[#00f9cb]' : 'bg-[#006853]'}`} />
              <span className={`text-xs font-label-caps font-semibold ${isDark ? 'text-white/90' : 'text-[#00352f]'}`}>
                {t.saver.difficulty}
              </span>
            </div>
          </div>

          {/* Servings and Time summary */}
          <div className="flex items-center justify-around text-center text-xs pt-1">
            <div className={`flex items-center gap-1.5 font-semibold ${isDark ? 'text-white/70' : 'text-[#00352f]'}`}>
              <span className={`material-symbols-outlined text-base ${isDark ? 'text-[#00f9cb]' : 'text-[#006853]'}`}>timer</span>
              <span>min 45</span>
            </div>
            <div className={`flex items-center gap-1.5 font-semibold ${isDark ? 'text-white/70' : 'text-[#00352f]'}`}>
              <span className={`material-symbols-outlined text-base ${isDark ? 'text-[#00f9cb]' : 'text-[#006853]'}`}>restaurant</span>
              <span>4 {isArabic ? 'أشخاص' : 'servings'}</span>
            </div>
          </div>
        </div>
      )}
    </div>
  );
};

